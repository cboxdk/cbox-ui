/** The icon for a name: the host's map first, then the built-in one, then a plain circle. */
export function resolveIcon(name: string | undefined, extra: Readonly<Record<string, ShellIcon>> = {}): ShellIcon {
    if (name === undefined) return Circle;
    return extra[name] ?? SHELL_ICONS[name] ?? Circle;
}
